#!/usr/bin/env python3
"""PRBS31, true in-netlist MOS phase-actuator servo gain/RC robustness.

The physical MOS TX, half-rate MOS RX latches, XSPICE 450MHz reference PLL,
MOS charge pump, MOS ring, and TWO current-starved MOS clock delay stages are
in one ngspice transient. The RX-only data-driven phase detector is a
*behavioral* B-source, and its charge-integrating capacitor is physical.

This follows the first 2026-11-12 phase-servo run: with PRBS7 the best
static fixed-gain feedback reduced 31/156 to 9/156 but never demonstrated
fully locked CDR. This new experiment:
  - uses a nonrepeating 256-bit PRBS31 pattern, seed fixed independently
  - tests both adverse start phases and zero-gain controls
  - changes only gain and analog integrator capacitor
  - counts missed, duplicated and not-regenerated physical samples
  - must not call a PLL-frequency success a 'data CDR lock'

It tests functional timing-recovery sensitivity, not exact Wong Fig.19
4-XOR logic, original phase interpolator or BER < 1e-12.
"""
from __future__ import annotations
import argparse,json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/"simulation"))
import p3_transistor_driver as TX
import p3_live_mos_phase_servo as S

SEEDS=(0x54C4EE17,0x13572468)
GAINS=(-200.,0.,80.,120.,160.,200.)
CAPS_PF=(.4,.8,1.6)
SHIFTS=(-.05,.95)

def prbs31(n,seed):
    state=seed&((1<<31)-1)
    if state==0:raise ValueError("LFSR seed zero")
    data=[]
    for i in range(n):
        data.append(state&1)
        state=((state<<1)&((1<<31)-1))|(((state>>30)^(state>>27))&1)
    return data

def run(out,seed,gain,cap,shift):
    if seed not in SEEDS or gain not in GAINS or cap not in CAPS_PF or shift not in SHIFTS:
        raise ValueError("invalid preset parameter")
    # Underlying link generated by the prior MOS source. Alter only input PRBS,
    # controller cap/gain, and initial bit-timing offset.
    old=(TX.prbs7,S.GAINS_UA,S.SHIFTS,S.C_F)
    try:
        TX.prbs7=lambda n:prbs31(n,seed)
        S.GAINS_UA=GAINS
        S.SHIFTS=SHIFTS
        S.C_F=cap*1e-12
        case=f"seed{seed:08X}_C{cap:.1f}pF_G{gain:+.0f}_shift{shift:+.2f}".replace("+","p").replace("-","m")
        result=S.main(out/case,gain,shift)
    finally:
        TX.prbs7,S.GAINS_UA,S.SHIFTS,S.C_F=old
    hold=result["coverage_aware"]["holdout"]
    item={
      "seed_hex":hex(seed),"input_data":"PRBS31","gain_uA":gain,
      "phase_integrator_C_pF":cap,"initial_data_timing_UI":shift,
      "holdout":hold,"MOS_VCO_GHz":result["VCO"]["vco_GHz"],
      "loop_gate_start_V":result["actuator_start_ctrl_V"],
      "loop_gate_last_V":result["actuator_last_ctrl_V"],
      "physical_MOS_in_netlist":True,
      "RX_phase_detector_transistor_logic":False,
      "CDR_lock_claim":False
    }
    (out/case/"robustness_summary.json").write_text(json.dumps(item,indent=2)+"\n")
    print(f"MOS_DATA_CDR_PRBS31 seed={seed:#x} gain_uA={gain} C_pF={cap} "
          f"shift_UI={shift} error={hold['total_invalid']}/{hold['expected']} "
          f"missing={hold['missing']} wrong={hold['wrong_regenerated']} "
          f"unresolved={hold['unresolved']} "
          f"VCO_GHz={item['MOS_VCO_GHz']}",flush=True)
    return item

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--seed",type=lambda x:int(x,0),choices=SEEDS,required=True)
    p.add_argument("--gain",type=float,choices=GAINS,required=True)
    p.add_argument("--cap",type=float,choices=CAPS_PF,required=True)
    p.add_argument("--shift",type=float,choices=SHIFTS,required=True)
    p.add_argument("--out",type=Path,default=Path("results/spice/p3_prbs31_live_MOS_CDR"))
    a=p.parse_args()
    run(a.out,a.seed,a.gain,a.cap,a.shift)
