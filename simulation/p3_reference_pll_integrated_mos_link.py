#!/usr/bin/env python3
"""One ngspice mixed-mode circuit: MOS TX + RC2 + MOS RX + XSPICE PFD/4
+ physical switched 7-bit MOS charge pump + physical CMOS ring VCO.

This study electrically connects the reference-PLL's MOS clock buffers
to the 3.6Gb/s MOS receiver; unlike earlier external free-running VCO
bias calibration, the PFD/charge-pump/loop filter feedback is in SPICE.

IMPORTANT: The reference PLL compares VCO/4 against an ideal 450MHz
clock. It is NOT a real-time CDR tracking serial data transitions.
The RX sampling phase is evaluated at a FIXED delay from actual physical
MOS clock transitions, with integer frame alignment only for scoring.
The channel and TX gate drive remain idealized, not paper silicon.
"""
from __future__ import annotations
import argparse,csv,json,math,re,shutil
from pathlib import Path
from bisect import bisect_left
import p3_transistor_driver as TX
import p3_integrated_mos_link as LINK
import p3_xspice_physical_mos_pll as PLL

CLOCK_REF_MHZ=450.
BITS=256
START_DATA_NS=1220.
DATA_END_DELAY_NS=2.
RX_READ_AFTER_FALL_UI=.75
MOS_REGENERATED_THRESHOLD_V=.15
SCORE_SKIP=18
CORNER="tt"
CODE=63

def netlist(bits,alpha=.3,start_ns=START_DATA_NS):
    deck=PLL.circuit(CODE,corner=CORNER)
    # TX/RC/RX portion generated by the previously VERIFIED MOS link.
    source=LINK.generate(bits,alpha,corner=CORNER)
    body=source.split(".control",1)[0]
    exclude=[
       ".include ", ".temp ","VDD vdd 0","VCLKeven ","VCLKodd "
    ]
    lines=[line for line in body.splitlines()
           if line.strip() and not any(line.startswith(k) for k in exclude)]
    # Shift all data-dependent PWL changes so that the reference PLL
    # has 1.22us to acquire the clock before the data burst begins.
    temp="\n".join(lines)+"\n"
    def shift(match):
        t=float(match.group(2))+start_ns*1e3
        return f"{match.group(1)}{t:.9f}p{match.group(3)}"
    temp,n=re.subn(r"(?m)^(\+\s+)([\d.]+)p(\s+[-\d.+Ee]+)",
                    shift,temp)
    if n<500:raise RuntimeError(f"Only {n} TX PWL steps were shifted")
    extras=[
        "* Actual MOS TX to full-complex modeled RC2 receive channel",
        temp,
        "* Physical MOS inverter outputs provide complementary half-rate RX clocks",
        "XPCLK_E clkeven n1 vdd vdd 0 pch_svt_1p8v width=6u length=.18u multi=1",
        "XNCLK_E clkeven n1 0 0 nch_svt_1p8v width=3u length=.18u multi=1",
        "XPCLK_O clkodd clkeven vdd vdd 0 pch_svt_1p8v width=6u length=.18u multi=1",
        "XNCLK_O clkodd clkeven 0 0 nch_svt_1p8v width=3u length=.18u multi=1",
    ]
    deck=deck.replace(".control","\n".join(extras)+"\n.control",1)
    orig="wrdata physical_pll.csv time v(n1) v(refclk) v(loopctrl) v(vcobias) v(upbar) v(dngate) i(vdd)"
    repl=("wrdata pll_driven_rx_wave.csv time v(n1) v(refclk) "
          "v(vcobias) v(rx) v(qeven) v(qbeven) "
          "v(qodd) v(qbodd) v(clkeven) v(clkodd) i(vdd) i(vsup)")
    if orig not in deck:raise ValueError("Original PLL waveform sink missing")
    deck=deck.replace(orig,repl)
    total_ns=start_ns+BITS*TX.UI_PS*1e-3+DATA_END_DELAY_NS
    deck,n=re.subn(r"(?m)^tran 3p [\d.]+n uic$",
                    f"tran 3p {total_ns:.9f}n uic",deck)
    if n!=1:raise ValueError(f"Unexpected PLL transient statement edits {n}")
    return deck

def read(path):
    result=[]
    for line in path.read_text().splitlines():
        try: a=[float(x) for x in line.split()]
        except ValueError:continue
        if len(a)>=26 and all(math.isfinite(x) for x in a):
            result.append({
                "time_s":a[0],"vco_V":a[3],"reference_V":a[5],
                "vco_control_V":a[7],"rx_V":a[9],
                "qeven_V":a[11],"qbeven_V":a[13],
                "qodd_V":a[15],"qbodd_V":a[17],
                "clkeven_V":a[19],"clkodd_V":a[21],
                "power_vdd_source_A":a[23],"power_tx_source_A":a[25]
            })
    if len(result)<5000:raise RuntimeError("No complete MOS TX/RX/PLL waveform")
    return result

def rising(rows,field,after_s):
    events=[]
    for a,b in zip(rows,rows[1:]):
        if a["time_s"]<after_s:continue
        if a[field]<.9<=b[field]:
            t=a["time_s"]+(.9-a[field])*(b["time_s"]-a["time_s"])/(b[field]-a[field])
            events.append(t)
    return events

def falling(rows,field,after_s):
    events=[]
    for a,b in zip(rows,rows[1:]):
        if a["time_s"]<after_s:continue
        if a[field]>=.9>b[field]:
            events.append(a["time_s"]+(.9-a[field])*(b["time_s"]-a["time_s"])/(b[field]-a[field]))
    return events

def frequency(rows):
    osc=rising(rows,"vco_V",after_s=(START_DATA_NS-35)*1e-9)
    ref=rising(rows,"reference_V",after_s=(START_DATA_NS-35)*1e-9)
    if len(osc)<40 or len(ref)<10:raise RuntimeError("Cannot measure settled 450-MHz PLL")
    r=[b-a for a,b in zip(osc,osc[1:])]
    d=sum(r)/len(r)
    edges=osc
    from bisect import bisect_left
    delta=[]
    for t in ref:
        k=bisect_left(edges,t)
        if 0<k<len(edges):
            phase=min([edges[k-1]-t,edges[k]-t],key=abs)
            delta.append(phase*1e12)
    avg=sum(delta)/len(delta)
    return {"vco_GHz":1/d/1e9,
            "reference_MHz":1/((ref[-1]-ref[0])/(len(ref)-1))/1e6,
            "phase_standard_deviation_ps":(sum((x-avg)**2 for x in delta)/len(delta))**.5,
            "vco_gate_mean_V":sum(x["vco_control_V"] for x in rows[-2500:])/2500}

def interp(rows,t,field,times):
    idx=bisect_left(times,t)
    if idx<=0 or idx>=len(rows):return float("nan")
    a,b=rows[idx-1],rows[idx]
    u=(t-a["time_s"])/(b["time_s"]-a["time_s"])
    return a[field]+(b[field]-a[field])*u

def evaluate(rows,bits,start_ns):
    times=[r["time_s"] for r in rows]
    t0=start_ns*1e-9
    scores=[]
    for lane,clk,q,qb in (
        ("even","clkeven_V","qeven_V","qbeven_V"),
        ("odd","clkodd_V","qodd_V","qbodd_V")):
        for edge in falling(rows,clk,t0+SCORE_SKIP*TX.UI_PS*1e-12):
            t=edge+RX_READ_AFTER_FALL_UI*TX.UI_PS*1e-12
            symbol=int(round((t-t0)/TX.UI_PS/1e-12))
            if not (SCORE_SKIP <= symbol < len(bits)-10):continue
            out=interp(rows,t,q,times)-interp(rows,t,qb,times)
            if not math.isfinite(out):continue
            scores.append({"physical_clock_sample_s":t,"lane":lane,
                "estimated_symbol_index":symbol,
                "Q_minus_QB_V":out,"mos_decoded_bit":int(out>0),
                "regenerated":int(abs(out)>=MOS_REGENERATED_THRESHOLD_V)})
    scores.sort(key=lambda r:r["physical_clock_sample_s"])
    lags=[]
    for lag in range(-5,6):
        errs=0
        for x in scores:
            idx=x["estimated_symbol_index"]+lag
            errs+=int(idx<0 or idx>=len(bits) or
                      not x["regenerated"] or x["mos_decoded_bit"]!=bits[idx])
        lags.append({"postrun_integer_frame_alignment":lag,"errors_including_unresolved":errs})
    if not scores:raise RuntimeError("No real MOS RX samples could be assigned")
    best=min(lags,key=lambda r:(r["errors_including_unresolved"],abs(r["postrun_integer_frame_alignment"])))
    return scores,{
        "samples_scored":len(scores),
        "best_integer_frame_alignment_for_postrun_scoring":best["postrun_integer_frame_alignment"],
        "bit_errors_including_unresolved":best["errors_including_unresolved"],
        "unresolved_MOS_latch_samples":sum(not x["regenerated"] for x in scores),
        "no_data_label_used_in_PFD":True,
        "receiver_phase_controller":"450MHz XSPICE PFD/4 only; no actual serial-data BBPD",
        "fixed_sample_after_physical_clock_fall_UI":RX_READ_AFTER_FALL_UI,
    }

def time_weighted_power_mW(rows,branch,supply_V):
    """Time-integrated actual SPICE branch source power, NOT sample mean."""
    area=sum(.5*(a[branch]+b[branch])*(b["time_s"]-a["time_s"])
             for a,b in zip(rows,rows[1:]))
    dur=rows[-1]["time_s"]-rows[0]["time_s"]
    if dur<=0:raise ValueError("Missing source-current waveform duration")
    return -area/dur*supply_V*1e3


def save(path,rows):
    if not rows:return
    with path.open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]))
        w.writeheader();w.writerows(rows)

def run(out):
    out.mkdir(parents=True,exist_ok=True)
    working=TX.ENGINE_DIR/"p3_physical_reference_pll_integrated"
    runner=TX.SpiceRunner(working)
    source=TX.model_path(CORNER)
    dest=working/source.name
    if not dest.exists() or source.stat().st_mtime>dest.stat().st_mtime:
        shutil.copy2(source,dest)
    bits=TX.prbs7(BITS)
    cases={}
    for name,alpha in (("ffe_0p30",.30),):
        runner.run(netlist(bits,alpha),f"whole_mos_pll_{name}")
        rows=read(working/"pll_driven_rx_wave.csv")
        pll=frequency(rows)
        samples,rx=evaluate(rows,bits,START_DATA_NS)
        power_window=[row for row in rows
                      if row["time_s"]>=START_DATA_NS*1e-9]
        partial_power={
            "1p8V_VDD_mW":time_weighted_power_mW(
                 power_window,"power_vdd_source_A",1.8),
            "0p5V_TX_signaling_supply_mW":time_weighted_power_mW(
                 power_window,"power_tx_source_A",.5)
        }
        partial_power["reported_partial_total_mW"]=(
            partial_power["1p8V_VDD_mW"]+
            partial_power["0p5V_TX_signaling_supply_mW"])
        rx["all_digital_decisions_correct_and_regenerated"]=bool(
            rx["bit_errors_including_unresolved"]==0 and
            rx["unresolved_MOS_latch_samples"]==0)
        cases[name]={"pll":pll,"physical_mos_rx":rx,
                     "time_weighted_partial_source_power":partial_power}
        save(out/f"{name}_mos_clocked_receiver_decisions.csv",samples)
        # Preserve 1 in 10 points of the final waveform data interval.
        focus=[row for row in rows if row["time_s"]>=(START_DATA_NS-3)*1e-9]
        save(out/f"{name}_mos_reference_pll_waveform.csv",focus[::10])
        print(f"FULL MOS TX/RX with 450MHz XSPICE PLL {name}: "
              f"fVCO={pll['vco_GHz']:.6f}GHz, phase std={pll['phase_standard_deviation_ps']:.3f}ps, "
              f"MOS RX errors={rx['bit_errors_including_unresolved']}/{rx['samples_scored']}",
              flush=True)
    report={
       "status":"executed_reference_PFD_physical_MOS_CP_VCO_plus_MOS_TX_RX_in_ONE_ngspice",
       "physical":"DB HiTek 180nm MOS TX, PMOS-input two-lane RX, 7-bit MOS charge pump and ring VCO",
       "digital":"XSPICE 2-DFF phase-frequency detector and 4-divider",
       "reference_MHz":CLOCK_REF_MHZ,"baud_Gbps":3.6,
       "data_starts_ns":START_DATA_NS,
       "ideal_elements":["450MHz crystal reference PULSE","TX 1.8V gate PWL drivers",
                         "Two-pole buffered RC channel","MOS VCO's isolated third-pole RC filter"],
       "NOT_an_actual_data_CDR":True,
       "power_scope":"Actual 1.8-V VDD branch for oscillator/MOS pump/clock buffers/RX plus 0.5-V MOS TX signaling source during data burst; excludes ideal TX gate drivers, termination bias and reference oscillator.",
       "postrun_integer_frame_alignment_only":True,
       "cases":cases,"ngspice_runs":runner.calls,
       "limitations":[
          "PFD locks 450MHz divided VCO, not data transitions; serial data clock phase not actively recovered",
          "No real original BBPD counter connected in SPICE",
          "Not original 2004 fabrication PDK/impedance regulators/switch-capacitor notch filter",
          "128/256 PRBS short test not BER 1e-12, receiver clock phase not calibrated in hardware",
          "ngspice HSPICE-only parameters ignored; device correlation pending"
       ]
    }
    (out/"reference_pll_mos_link_summary.json").write_text(json.dumps(report,indent=2)+"\n")
    pllcase=cases["ffe_0p30"]["pll"]
    if abs(pllcase["vco_GHz"]-1.8)>=.025 or pllcase["phase_standard_deviation_ps"]>=8:
        raise AssertionError("MOS TX/RX loading prevents physical PLL frequency/phase lock")
    print("PASS: physical reference PLL frequency and phase locked in single MOS TX/RX netlist",flush=True)
    if not cases["ffe_0p30"]["physical_mos_rx"]["all_digital_decisions_correct_and_regenerated"]:
        print("LIMITATION: clocked MOS RX has residual data errors; a real data CDR is still required",flush=True)
    return report

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--out",type=Path,
      default=Path("results/spice/p3_reference_pll_mos_link"))
    run(p.parse_args().out)
